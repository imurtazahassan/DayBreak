export function buildDemoEdition(): Edition {
  const today = toDateKey(new Date())
  return {
    id: `demo-edition-${today}`,
    editionDate: today,
    editionNumber: 1,
    readerId: 'default',
    createdAt: new Date().toISOString(),
    items: DEMO_ARTICLES.map((article, i) => ({
      articleId: article.id,
      article,
      rank: i + 1,
      size: i === 0 ? 'lead' : i <= 2 ? 'featured' : i <= 6 ? 'standard' : 'brief',
      sectionKey: i === 0 ? 'lead' : article.categories[0],
      scoreBreakdown: {
        interestWeight: 0.8 - i * 0.05,
        recencyScore: 1 - i * 0.05,
        sourcePreference: 0.75,
        diversityPenalty: 0,
        explorationBonus: i === 7 ? 0.1 : 0,
        totalScore: 0.9 - i * 0.05,
      },
    })),
    sectionOrder: ['lead', 'technology', 'climate', 'pakistan', 'business', 'science', 'world', 'sports'],
    totalReadingMinutes: DEMO_ARTICLES.reduce((s, a) => s + a.readingTimeMinutes, 0),
    label: 'demo',
    isDemo: true,
  }
}
